import { GLOSSARY, PROSE } from './prose';
import { parseMd, plain } from './md';
import { table } from './md';
import { buildKit, domeTiers } from './gen/build';
import { chips, drawerPages, drawers, hotkeys, operationalRows, quality } from './gen/hud';
import { shopFood, shopGoods, shopOther, shopPresets } from './gen/shop';
import { difficulty, lifestyles, lots, modes, peace, regions, richStarts } from './gen/world';
import { disasters, storms, tracks, yearlyThreats } from './gen/threats';
import { gateChoices, orders, scouts, stages } from './gen/raids';
import { utilityBuildings, utilityFacts } from './gen/utilities';
import type { Generator, Manual, ManualSection } from './types';

/** Every generated block, by name. A `{{gen:name}}` in the prose expands to the generator's output between markers. */
export const GENERATORS: Record<string, Generator> = {
  operational: operationalRows, 'utility-facts': utilityFacts, 'utility-buildings': utilityBuildings,
  chips, drawers, 'drawer-pages': drawerPages, hotkeys, quality,
  modes, peace, difficulty, regions, lots, lifestyles, 'rich-starts': richStarts,
  'shop-presets': shopPresets, 'shop-food': shopFood, 'shop-goods': shopGoods, 'shop-other': shopOther,
  'build-kit': buildKit, 'dome-tiers': domeTiers,
  tracks, disasters, storms, 'yearly-threats': yearlyThreats,
  'gate-choices': gateChoices, scouts, orders, stages,
  glossary: () => table(['Term', 'Meaning'], GLOSSARY.map(([t, m]) => [t, m])),
};

const TOKEN = /\{\{gen:([a-z-]+)\}\}/g;
export const markerOpen = (n: string) => `<!-- gen:${n} -->`;
export const markerClose = (n: string) => `<!-- /gen:${n} -->`;

/** Names of the generators the prose asks for. */
export function usedGenerators(): string[] {
  return PROSE.flatMap(s => [...s.md.matchAll(TOKEN)].map(m => m[1]));
}

function expand(md: string): string {
  return md.replace(TOKEN, (_, name: string) => {
    const g = GENERATORS[name];
    if (!g) throw new Error(`manual: the prose uses {{gen:${name}}} but no generator has that name`);
    return `${markerOpen(name)}\n${g().trim()}\n${markerClose(name)}`;
  });
}

const HEADER = `# Compound Builder: Player Manual

> Generated by \`npm run manual\` from the game's own data. Do not edit the text between \`<!-- gen:... -->\` markers: change the data or the generator, then run the command. The prose around the tables is in \`src/manual/prose.ts\`. The same text is in the game as the Field Guide (press I).
`;

/** The whole manual, in memory. Pure and deterministic. */
export function buildManual(): Manual {
  const sections: ManualSection[] = PROSE.map(s => ({ id: s.id, title: s.title, about: s.about, md: expand(s.md) }));
  const toc = sections.map((s, i) => `${i + 1}. ${s.title}: ${s.about}`).join('\n');
  const markdown = [HEADER, '## Contents', '', toc, '', ...sections.map(s => `## ${s.title}\n\n${s.md}\n`)].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
  return { sections, markdown };
}

export interface Hit { section: string; title: string; text: string }
/** Every chunk of the manual that holds all the words of `q` (a paragraph, a bullet, or a table row with its first cell). */
export function searchManual(sections: readonly ManualSection[], q: string, limit = 40): Hit[] {
  const ws = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!ws.length) return [];
  const out: Hit[] = [];
  for (const s of sections) {
    const chunks: string[] = [];
    for (const b of parseMd(s.md)) {
      if (b.t === 'p' || b.t === 'h3') chunks.push(plain(b.text));
      else if (b.t === 'ul') b.items.forEach(i => chunks.push(plain(i)));
      else b.rows.forEach(r => chunks.push(r.map(plain).join(': ')));
    }
    for (const c of chunks) {
      const low = `${s.title} ${c}`.toLowerCase();
      if (ws.every(w => low.includes(w))) { out.push({ section: s.id, title: s.title, text: c }); if (out.length >= limit) return out; }
    }
  }
  return out;
}
